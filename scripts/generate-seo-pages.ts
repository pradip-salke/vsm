// Regenerates packages/contracts/src/seo-pages-data.ts from the website's dynamic route content
// (specialisation pages and gallery albums). Run: node node_modules/tsx/dist/cli.mjs scripts/generate-seo-pages.ts
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { academicSpecialisations } from '../apps/web/content/academic-specialisations';
import { archiveEvents, eventDetails, galleryEvents } from '../apps/web/content/events';

const slugOf = (href: string) => href.split('/').filter(Boolean).at(-1)!;

const specialisations = academicSpecialisations.map(({ slug, heroTitle }) => ({ path: `/our-academics/in-demand-specialisations/${slug}/`, label: heroTitle }));

const albums = new Map<string, string>();
for (const event of [...galleryEvents, ...archiveEvents]) albums.set(slugOf(event.href), event.title);
for (const [slug, event] of Object.entries(eventDetails)) if (!albums.has(slug)) albums.set(slug, event.title);
const gallery = [...albums].map(([slug, label]) => ({ path: `/gallery/${slug}/`, label }));

const out = `// Generated by scripts/generate-seo-pages.ts — do not edit by hand.
export const seoSpecialisationPages: { path: string; label: string }[] = ${JSON.stringify(specialisations, null, 2)};

export const seoGalleryAlbumPages: { path: string; label: string }[] = ${JSON.stringify(gallery, null, 2)};
`;
writeFileSync(resolve(import.meta.dirname, '../packages/contracts/src/seo-pages-data.ts'), out, 'utf8');
console.log(`Wrote ${specialisations.length} specialisation and ${gallery.length} gallery album URLs.`);
